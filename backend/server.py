@api_router.get("/pdf-health")
async def pdf_health():
    """Diagnostic endpoint — reports everything the PDF pipeline depends on
    so we can pinpoint production failures without a redeploy. Safe to
    expose: contains no secrets, just paths/counts/booleans."""
    from pdf_builder import (
        _autodetect_chromium_path,
        _chromium_ready,
        _try_launch_chromium,
    )

    info: dict[str, Any] = {
        # Which renderer the worker will use for the next export. Set
        # via PDF_ENGINE env var; defaults to `weasy` (pure-Python,
        # never hangs the way Chromium did on this pod).
        "pdf_engine": (os.environ.get("PDF_ENGINE") or "weasy").lower(),
        "playwright_browsers_path_env": os.environ.get("PLAYWRIGHT_BROWSERS_PATH"),
        "detected_browsers_path": _autodetect_chromium_path(),
        "chromium_ready_cached": _chromium_ready,
        "python": f"{__import__('sys').version_info.major}.{__import__('sys').version_info.minor}",
        # MongoDB target — same redacted string we log at startup. The
        # value MUST be identical across every pod behind the load
        # balancer; if /api/pdf-health on two consecutive requests
        # returns DIFFERENT `mongo_target` strings, you have a
        # multi-pod-DB split and counts WILL diverge no matter what
        # the query layer does. Reading this value from a browser is
        # the diagnostic the user can run without SSH access.
        "mongo_target": _redact_mongo_url(mongo_url),
        "mongo_db_name": os.environ['DB_NAME'],
    }
    # WeasyPrint probe — confirm the engine module imports and reports
    # its version. A failure here means the install is broken on the
    # pod and exports will fall back to Chromium (or fail outright).
    try:
        import weasyprint as _wp
        info["weasyprint_version"] = _wp.__version__
        info["weasyprint_ready"] = True
    except Exception as e:
        info["weasyprint_version"] = None
        info["weasyprint_ready"] = False
        info["weasyprint_error"] = str(e)[:200]
    # Google Fonts cache probe — Support pinpointed Google Fonts
    # fetches as the cause of full-book hangs. We pre-warm a local
    # WOFF2 cache at startup. This probe surfaces whether the cache
    # populated successfully or whether renders are running in the
    # degraded "system fonts only" fallback mode.
    try:
        from fonts_cache import _inlined_css, _inline_attempt_failed, _woff2_cache
        info["fonts_cache_ready"] = _inlined_css is not None and bool(_inlined_css)
        info["fonts_cache_failed"] = _inline_attempt_failed
        info["fonts_cache_woff2_count"] = len(_woff2_cache)
        info["fonts_cache_css_bytes"] = len(_inlined_css or "")
    except Exception as e:
        info["fonts_cache_error"] = str(e)[:200]
    # Ghostscript probe — Print-ready (PDF/X-1a) exports fail silently
    # without `gs`. We detect via `gs --version` because some images
    # ship a non-executable `gs` stub from the apt index.
    try:
        import shutil as _shutil
        gs_path = _shutil.which("gs")
        info["ghostscript_path"] = gs_path
        if gs_path:
            try:
                proc = await asyncio.create_subprocess_exec(
                    gs_path, "--version",
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                )
                out, _ = await asyncio.wait_for(proc.communicate(), timeout=5)
                info["ghostscript_version"] = out.decode().strip()
            except Exception as e:
                info["ghostscript_version_error"] = str(e)[:200]
        # stdbuf — used to force line-buffered Ghostscript stdout so the
        # streaming progress bar updates in real time.
        info["stdbuf_path"] = _shutil.which("stdbuf")
    except Exception as e:
        info["ghostscript_probe_error"] = str(e)[:200]
    # Live launch probe — the cached flag can lie if the binary was wiped.
    try:
        info["chromium_launchable"] = await _try_launch_chromium()
    except Exception as e:
        info["chromium_launchable"] = False
        info["chromium_launch_error"] = str(e)[:300]

    # Disk + memory snapshot (helps identify OOM/disk-full failures).
    try:
        import shutil
        du = shutil.disk_usage("/")
        info["disk_total_mb"] = du.total // (1024 * 1024)
        info["disk_free_mb"] = du.free // (1024 * 1024)
    except Exception as e:
        info["disk_error"] = str(e)[:200]
    try:
        # /proc/meminfo is always present on Linux containers and avoids
        # pulling in psutil just for diagnostics.
        with open("/proc/meminfo") as f:
            mem: dict[str, int] = {}
            for line in f:
                parts = line.split()
                if len(parts) >= 2 and parts[0].rstrip(":") in {
                    "MemTotal", "MemAvailable", "MemFree", "SwapTotal", "SwapFree"
                }:
                    mem[parts[0].rstrip(":")] = int(parts[1]) // 1024  # kB → MB
            info["memory_mb"] = mem
    except Exception as e:
        info["memory_error"] = str(e)[:200]

    # Recent failed jobs (last 5) — fastest way to see what's been blowing up.
    # We also report `failed_count_total` so even after the 30-min TTL
    # purges old failures, a non-zero count is a flag that something has
    # been unstable. Helpful when a user reports "it kept failing" but the
    # `recent_failures` list is already empty.
    try:
        recent = await db.pdf_jobs.find(
            {"status": "failed"}, {"_id": 0, "job_id": 1, "book_id": 1,
                                    "error": 1, "stage": 1, "finished_at": 1},
        ).sort("finished_at", -1).to_list(5)
        info["recent_failures"] = recent
        info["failed_count_total"] = await db.pdf_jobs.count_documents({"status": "failed"})
        info["ready_count_total"] = await db.pdf_jobs.count_documents({"status": "ready"})
    except Exception as e:
        info["recent_failures_error"] = str(e)[:200]

    # Recent in-flight jobs (last 5 pending) — shows what's stuck.
    try:
        pending = await db.pdf_jobs.find(
            {"status": "pending"}, {"_id": 0, "job_id": 1, "book_id": 1,
                                     "stage": 1, "created_at": 1, "stage_at": 1},
        ).sort("created_at", -1).to_list(5)
        info["pending_jobs"] = pending
    except Exception as e:
        info["pending_jobs_error"] = str(e)[:200]

    return info





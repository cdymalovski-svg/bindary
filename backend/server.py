# ===== PDF export — job-based flow =====
# Job state must be SHARED across backend pods (production runs multiple
# replicas behind a load balancer — a job created on pod A must be
# pollable from pod B). We store status in MongoDB and the PDF bytes in
# object storage, the same way we handle book images.
_PDF_OBJECT_PREFIX = "booktemplate/pdfjobs"
# Split TTL for the pdf_jobs collection so we can retain failed/pending
# jobs long enough to actually diagnose them, while still auto-expiring
# successful jobs quickly (delivery only needs a short window).
#
# Semantics (enforced by writing `expires_at` on every state change,
# NOT by the index — the index just watches whatever datetime is in the
# field):
#   - insert (status: pending)  → expires_at = now + 7 days
#   - status: ready             → expires_at = now + 30 min
#   - status: failed/cancelled  → expires_at = now + 7 days
#
# Before this change every job was reaped 30 min after insert, so any
# production timeout that took longer than 30 min to look into was
# unreproducible. 7 days for failed jobs is the diagnostic window.
_PDF_JOB_TTL_READY_SECONDS = 30 * 60          # 30 min
_PDF_JOB_TTL_FAILED_SECONDS = 7 * 24 * 60 * 60  # 7 days


def _emit_job_summary(
    job_id: str,
    render_timings: dict,
    upload_s: Optional[float],
    upload_status: str,
) -> None:
    """Compose the authoritative end-of-job log line + persist it onto
    the pdf_jobs doc.

    `upload_status`:
      - "ok"        → emits "upload=X.XXs"
      - "TIMEOUT"   → emits "upload=FAILED (timeout after 120s)"
      - other       → emits "upload=FAILED (<status>)" — the caller passes
                       type(e).__name__ so operators see e.g.
                       "upload=FAILED (ConnectionError)"

    Fire-and-forget on the Mongo write — if we lose the doc update the
    log line itself is still there in supervisor logs and that's the
    authoritative record.
    """
    # `render_timings` may be empty if the render itself failed before
    # `summary_cb` fired — in that case the log line still goes out but
    # the render numbers show as "n/a".
    total_render_s = render_timings.get("total_render_s")
    prefetch_s = render_timings.get("prefetch_s")
    render_s = render_timings.get("render_s")
    pages = render_timings.get("pages")
    fonts_used = render_timings.get("fonts_used")
    fonts_missing = render_timings.get("fonts_missing")
    missing_families = render_timings.get("missing_font_families") or []

    def _fmt_s(v):
        return f"{v:.2f}s" if isinstance(v, (int, float)) else "n/a"

    if upload_status == "ok":
        upload_str = _fmt_s(upload_s)
    elif upload_status == "TIMEOUT":
        upload_str = "FAILED (timeout after 120s)"
    else:
        upload_str = f"FAILED ({upload_status})"

    # `total` here = prefetch + render + upload — the honest whole-job
    # wall clock. Deliberately different from the old summary's total
    # (which excluded upload); operators reading a new-format line will
    # see it labelled with all three components on the same line so it's
    # unambiguous.
    if isinstance(total_render_s, (int, float)) and isinstance(upload_s, (int, float)):
        grand_total = total_render_s + upload_s
        total_str = f"{grand_total:.2f}s"
    else:
        total_str = "n/a"

    missing_tail = f" {missing_families}" if missing_families else ""
    summary_text = (
        "WeasyPrint JOB SUMMARY: "
        f"total={total_str} | prefetch={_fmt_s(prefetch_s)} | "
        f"render={_fmt_s(render_s)} | upload={upload_str} | "
        f"pages={pages if pages is not None else 'n/a'} | "
        f"fonts: {fonts_used if fonts_used is not None else 'n/a'} used, "
        f"{fonts_missing if fonts_missing is not None else 'n/a'} missing"
        f"{missing_tail}"
    )
    logging.info(summary_text)
    # Persist onto the job doc so the admin "Recent exports" panel can
    # display it cross-pod. Fire-and-forget.
    asyncio.ensure_future(db.pdf_jobs.update_one(
        {"job_id": job_id},
        {"$set": {"summary": summary_text}},
    ))


async def _ensure_pdf_jobs_indexes() -> None:
    """Create the TTL index once so finished jobs auto-purge from Mongo.

    We drop-and-recreate the TTL index on every startup rather than
    attempting an in-place modification: MongoDB does not permit
    changing `expireAfterSeconds` on an existing TTL index (the driver
    silently no-ops), so drop → create is the correct sequence even
    when the *parameter* is identical. This keeps the index definition
    idempotent and defensively fresh across deploys. The TTL semantics
    themselves come from the per-document `expires_at` value written by
    the worker (see _PDF_JOB_TTL_*_SECONDS above) — the index just
    honours whatever datetime is in the field.
    """
    try:
        # Drop only if it exists. `drop_index` on a missing index raises
        # OperationFailure; swallow that specific case so first-ever boot
        # (no index yet) is a no-op.
        try:
            await db.pdf_jobs.drop_index("pdf_jobs_ttl")
        except Exception as e:
            # "index not found with name" is expected on first boot.
            if "index not found" not in str(e).lower():
                logging.warning(f"pdf_jobs_ttl drop skipped: {e}")
        await db.pdf_jobs.create_index(
            "expires_at", expireAfterSeconds=0, name="pdf_jobs_ttl"
        )
        await db.pdf_jobs.create_index("job_id", unique=True, name="pdf_jobs_job_id")
    except Exception as e:
        logging.warning(f"pdf_jobs index creation failed (probably already exists): {e}")


async def _run_pdf_job(
    job_id: str,
    book_id: str,
    base_url: str,
    start_page: Optional[int] = None,
    end_page: Optional[int] = None,
    pdfx: bool = False,
    cover_spread: bool = False,
    spine_width_in: Optional[float] = None,
    binding: str = "perfect",
    dpi: int = 300,
    preview: bool = False,
) -> None:
    """Background worker — builds the PDF, uploads bytes to object storage,
    flips the Mongo record to `ready` (or `failed`).

    `start_page` / `end_page` are 1-indexed INCLUSIVE. When provided, only
    those pages are rendered (the full book is loaded then the `pages` list
    is sliced before handing it to the builder — keeps page-numbering logic
    on the builder side simple: it always sees a contiguous `pages` array).

    `pdfx` runs the final PDF through Ghostscript to produce a print-ready
    PDF/X-1a:2001 file (CMYK, embedded fonts, transparency flattened,
    OutputIntent ICC profile baked in). Adds ~10–30s to export time.
    """
    # The actual engine import happens deeper in this function so it can
    # honour the PDF_ENGINE env-var. Don't import build_book_pdf here —
    # we route through `_build_book_pdf` after engine selection below.

    # Per-job stage tracker. Each call writes to Mongo so the polling client
    # can show "rendering chunk 3/8" instead of just an elapsed counter.
    # We coalesce updates so a callback storm doesn't hammer Mongo.
    last_stage: dict = {"v": None}

    class _Cancelled(Exception):
        """Raised by `_check_cancelled` when the user has clicked Cancel on
        the export toast. The except clause in the main worker catches it
        and flips the job to failed with a clean 'Cancelled by user'
        message — and crucially stops further Playwright/Ghostscript work
        so the pod's resources are freed immediately."""

    async def _check_cancelled() -> None:
        """Called at every coarse checkpoint in the main flow (between
        chunks, between major stages). Mongo round-trip is sub-ms locally
        so this is cheap. We avoid calling it from `_on_stage` because
        that's a sync callback executed from inside synchronous render
        code — we can't await there."""
        doc = await db.pdf_jobs.find_one(
            {"job_id": job_id}, {"_id": 0, "cancel_requested": 1}
        )
        if doc and doc.get("cancel_requested"):
            raise _Cancelled()

    def _on_stage(stage: str) -> None:
        if stage == last_stage["v"]:
            return
        last_stage["v"] = stage
        # Fire-and-forget; failures here must never break the render.
        # `ensure_future` accepts both coroutines and Motor's Future-like
        # objects (motor wraps Mongo ops in chained asyncio Futures, which
        # `create_task` rejects).
        asyncio.ensure_future(db.pdf_jobs.update_one(
            {"job_id": job_id},
            {"$set": {"stage": stage, "stage_at": _now_iso()}},
        ))

    try:
        book = await db.books.find_one({"id": book_id}, {"_id": 0})
        if not book:
            await db.pdf_jobs.update_one(
                {"job_id": job_id},
                {"$set": {"status": "failed", "error": "Book not found",
                          "finished_at": _now_iso()}},
            )
            return
        # Range bookkeeping. We do NOT slice `book["pages"]` here — the
        # builder needs the FULL array so it can preserve original page
        # numbers and original-length-based cover detection. We just clamp
        # the user-supplied range against the actual book length and pass
        # it down for the builder to slice internally.
        all_pages = book.get("pages") or []
        total = len(all_pages)
        applied_start = start_page if start_page is not None else 1
        applied_end = end_page if end_page is not None else total
        applied_start = max(1, min(applied_start, total))
        applied_end = max(applied_start, min(applied_end, total))
        is_range = start_page is not None or end_page is not None

        _on_stage("starting")
        await _check_cancelled()
        # PDF engine selection. WeasyPrint is the default — it's pure
        # Python (Cairo + Pango), never spawns a subprocess, and never
        # hangs the way Chromium has on production pods where
        # `asyncio.wait_for` can't actually cancel Playwright's
        # subprocess launch. Set PDF_ENGINE=chromium to force the
        # original Playwright pipeline (e.g. for visual A/B testing).
        engine = (os.environ.get("PDF_ENGINE") or "weasy").lower()
        if engine == "chromium":
            from pdf_builder import build_book_pdf as _build_book_pdf
            from pdf_builder import build_cover_spread_pdf as _build_cover_pdf
            _on_stage(f"engine: chromium")
        else:
            from pdf_builder_weasy import build_book_pdf as _build_book_pdf
            from pdf_builder_weasy import build_cover_spread_pdf as _build_cover_pdf
            _on_stage(f"engine: weasyprint")

        # Captured RENDER-side timings dict — populated by the summary
        # callback from `_build_book_pdf` (interior path only; cover
        # spreads leave it empty and the JOB SUMMARY log line reports
        # render fields as "n/a"). Defined here at the top of the
        # try-block so BOTH the cover-spread and interior branches can
        # safely reference it in the upload try/except below without
        # triggering "cannot access local variable 'render_timings'".
        render_timings: dict = {}

        if cover_spread:
            # Cover spread overrides any range — by definition it builds
            # the cover ONLY, using pages[0] and pages[-1].
            pdf_bytes = await _build_cover_pdf(
                book, get_object, public_base_url=base_url, progress_cb=_on_stage,
                spine_width_in=spine_width_in,
                binding=binding,
                dpi=dpi,
            )
        else:
            # Orphan-image diagnostic callback (passed only to the
            # weasy engine, which knows how to log per-path warnings).
            # Returns the set of paths that have NO row in db.files.
            # Does NOT block the export — the blank-PNG fallback in
            # the fetch path handles 404s. This callback exists purely
            # to make the failure mode visible at start instead of
            # mid-fetch. `is_deleted: True` rows count as missing
            # too — a soft-deleted file is functionally unavailable.
            async def _check_missing_paths(paths: list) -> set:
                if not paths:
                    return set()
                cur = db.files.find(
                    {"storage_path": {"$in": paths}, "is_deleted": {"$ne": True}},
                    {"_id": 0, "storage_path": 1},
                )
                existing = {row["storage_path"] async for row in cur}
                return set(paths) - existing

            # Capture the RENDER-side timings dict so we can emit the
            # authoritative JOB SUMMARY line AFTER the upload step
            # completes (or fails) — upload duration is the only piece
            # that's invisible to the render pipeline. The dict itself
            # is defined at the top of this try-block so the cover
            # spread branch can also reference it in the shared upload
            # error handler below.
            def _on_summary(timings: dict) -> None:
                render_timings.update(timings or {})

            pdf_bytes = await _build_book_pdf(
                book, get_object, public_base_url=base_url, progress_cb=_on_stage,
                start_page=applied_start if is_range else None,
                end_page=applied_end if is_range else None,
                dpi=dpi,
                # Print bleed / TrimBox stamping / even-page padding are
                # skipped in preview mode — the file is for on-screen
                # edit review, not for submission to the printer. This
                # halves render + memory in exchange for a non-print PDF.
                pdfx_bleed=(not preview),
                path_existence_check=_check_missing_paths,
                summary_cb=_on_summary if engine != "chromium" else None,
            )
        # Post-process to PDF/X-1a (CMYK, embedded fonts, OutputIntent) if
        # the caller requested a print-ready file. Runs only when the toggle
        # is on — for everyday previewing the raw RGB PDF is much faster.
        if pdfx:
            from pdfx_converter import convert_to_pdfx
            from pypdf import PdfReader
            from io import BytesIO
            # Read the page count out of the PDF we just rendered so the
            # streaming progress bar below has a denominator to count
            # against ("converting to PDF/X-1a (12/60)").
            try:
                total_pages_pdfx = len(PdfReader(BytesIO(pdf_bytes)).pages)
            except Exception:
                total_pages_pdfx = None
            await _check_cancelled()
            _on_stage("converting to PDF/X-1a")
            pdf_bytes = await convert_to_pdfx(
                pdf_bytes,
                title=book.get("title") or "book",
                total_pages=total_pages_pdfx,
                progress_cb=_on_stage,
            )
        await _check_cancelled()
        # File naming: prefer IngramSpark convention when ISBN is set on
        # the book (`{isbn}_txt.pdf` for interior, `{isbn}_cvr.pdf` for
        # cover spread). Falls back to the title-slug naming we've always
        # used so books without an ISBN still get a human-friendly name.
        raw_isbn = (book.get("isbn") or "").strip()
        # Validate as 10 or 13 digit ISBN (allow hyphens which we strip);
        # invalid → fall back to title naming so we never emit a weird
        # filename.
        isbn_digits = re.sub(r"[^0-9X]", "", raw_isbn.upper())
        use_isbn = len(isbn_digits) in (10, 13)
        safe_title = re.sub(r"[^A-Za-z0-9._-]+", "_", book.get("title") or "book").strip("_") or "book"
        base = isbn_digits if use_isbn else safe_title
        # "_pdfx" suffix makes print-ready exports unmistakable in Finder.
        pdfx_suffix = "_pdfx" if pdfx else ""
        # "-PREVIEW" suffix for low-res edit-review exports so nobody
        # accidentally submits one to IngramSpark.
        preview_suffix = "-PREVIEW" if preview else ""
        if cover_spread:
            # IngramSpark cover-file naming convention.
            suffix = "_cvr" if use_isbn else "_cov"
            filename = f"{base}{suffix}{pdfx_suffix}{preview_suffix}.pdf"
        else:
            # IngramSpark interior-file naming convention.
            interior_suffix = "_txt" if use_isbn and not is_range else ""
            if is_range:
                filename = f"{base}_pp_{applied_start}-{applied_end}{pdfx_suffix}{preview_suffix}.pdf"
            else:
                filename = f"{base}{interior_suffix}{pdfx_suffix}{preview_suffix}.pdf"
        # Upload PDF bytes to shared object storage so any pod can serve them.
        # We wrap the upload in a wall-clock timeout so a misbehaving
        # storage backend (network blip, slow upstream) can never leave
        # the job in `pending` forever — the user sees a clean failure
        # toast and can retry instead of waiting indefinitely.
        _on_stage("uploading")
        object_path = f"{_PDF_OBJECT_PREFIX}/{job_id}.pdf"
        # Time the upload separately so the authoritative JOB SUMMARY log
        # (emitted right below) can attribute wall-clock time to render vs. upload.
        upload_t0 = time.monotonic()
        upload_s: Optional[float] = None
        upload_status: str = "pending"  # "ok" | "TIMEOUT" | "<ExceptionName>"
        try:
            await asyncio.wait_for(
                asyncio.to_thread(put_object, object_path, pdf_bytes, "application/pdf"),
                timeout=120,
            )
            upload_s = time.monotonic() - upload_t0
            upload_status = "ok"
        except asyncio.TimeoutError:
            upload_s = time.monotonic() - upload_t0
            upload_status = "TIMEOUT"
            _emit_job_summary(job_id, render_timings, upload_s, upload_status)
            raise RuntimeError(
                "PDF upload to object storage timed out after 2 min — "
                "storage backend may be unavailable. Please try again."
            ) from None
        except Exception as e:
            upload_s = time.monotonic() - upload_t0
            upload_status = type(e).__name__
            _emit_job_summary(job_id, render_timings, upload_s, upload_status)
            raise
        # Successful upload — emit the authoritative summary line now
        # (before the "mark ready" write, so even a Mongo blip below still
        # leaves the summary in supervisor logs and persisted onto the job doc).
        _emit_job_summary(job_id, render_timings, upload_s, upload_status)
        await db.pdf_jobs.update_one(
            {"job_id": job_id},
            {"$set": {
                "status": "ready",
                "stage": "ready",
                "size": len(pdf_bytes),
                "filename": filename,
                "start_page": applied_start,
                "end_page": applied_end,
                "object_path": object_path,
                "finished_at": _now_iso(),
                # READY window — the client has ~30 min to download.
                # Anything after that we consider abandoned; the doc TTLs
                # out so the collection stays lean.
                "expires_at": datetime.now(timezone.utc) + timedelta(seconds=_PDF_JOB_TTL_READY_SECONDS),
            }},
        )
    except _Cancelled:
        # User clicked the X on the export toast. Flip the job to a clean
        # 'failed' state with a friendly reason — the frontend special-
        # cases this string to show "Export cancelled" instead of the
        # alarming red error toast.
        logging.info("PDF job %s cancelled by user", job_id)
        await db.pdf_jobs.update_one(
            {"job_id": job_id},
            {"$set": {"status": "failed",
                      "error": "Cancelled by user",
                      "finished_at": _now_iso(),
                      # FAILED window — 7 days so an operator can find
                      # this in the recent-exports admin panel.
                      "expires_at": datetime.now(timezone.utc) + timedelta(seconds=_PDF_JOB_TTL_FAILED_SECONDS)}},
        )
    except Exception as e:
        # Capture a snippet of the traceback so the client toast can show
        # something more useful than a generic "build failed". Truncate
        # heavily — the full trace is in logs, the toast just needs a hint.
        import traceback
        tb = traceback.format_exc().splitlines()
        last_lines = " | ".join(tb[-3:]) if tb else ""
        logging.exception("PDF job %s failed", job_id)
        await db.pdf_jobs.update_one(
            {"job_id": job_id},
            {"$set": {"status": "failed",
                      "error": f"{e}".strip()[:300] or "PDF build failed",
                      "trace": last_lines[:500],
                      "finished_at": _now_iso(),
                      # FAILED window — 7 days so an operator can find
                      # this in the recent-exports admin panel.
                      "expires_at": datetime.now(timezone.utc) + timedelta(seconds=_PDF_JOB_TTL_FAILED_SECONDS)}},
        )


class PdfJobStartRequest(BaseModel):
    """Optional 1-indexed inclusive page range. Both omitted = full book.
    `pdfx=true` runs the final PDF through Ghostscript to produce a
    PDF/X-1a:2001-compliant CMYK file ready for commercial printing.
    `cover_spread=true` builds a print-ready cover spread PDF (back +
    spine + front, with 0.125" bleed all around) instead of the
    interior. `spine_width_in` overrides the auto-computed spine width
    when the user knows their printer's paper caliper exactly."""
    model_config = ConfigDict(extra="ignore")
    start_page: Optional[int] = None
    end_page: Optional[int] = None
    pdfx: bool = False
    cover_spread: bool = False
    spine_width_in: Optional[float] = None
    # `perfect` (default) or `casebound`. Only meaningful when
    # `cover_spread=True`. Casebound adds 0.625" wrap (turn-in) instead
    # of 0.125" bleed and widens the spine by 0.125" for the spine board.
    binding: Optional[str] = "perfect"
    # Image-downscale ceiling expressed in DPI: 300 (default, prod-safe),
    # 450 (high), or 600 (maximum). Higher values keep more pixel detail
    # in the embedded artwork at the cost of render time + PDF size.
    # Anything else snaps to 300.
    dpi: Optional[int] = 300
    # Low-res preview mode — for edit review only. Skips TrimBox/BleedBox
    # stamping, skips the even-page-count padding, skips PDF/X conversion,
    # and clamps DPI to 150 regardless of the `dpi` field above. Produces
    # a small, fast PDF the user can flick through and mark up; NOT for
    # submission to IngramSpark. Filename gets a `-PREVIEW` suffix.
    preview: bool = False



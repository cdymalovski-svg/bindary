def _now_iso():
    return datetime.now(timezone.utc).isoformat()


class Block(BaseModel):
    model_config = ConfigDict(extra="ignore")
    id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    type: str  # 'text' | 'image'
    x: float = 40
    y: float = 40
    width: float = 300
    height: float = 120
    z_index: int = 1
    # Text block
    html: Optional[str] = ""
    font_family: Optional[str] = "Cormorant Garamond"
    font_size: Optional[int] = 18
    text_align: Optional[str] = "left"
    color: Optional[str] = "#000000"
    # Image block
    image_url: Optional[str] = None
    image_path: Optional[str] = None
    # Optional solid background fill rendered behind the image. Works
    # for both image blocks (visible through transparent PNG regions —
    # e.g. a hand-drawn illustration over a coloured backdrop) and
    # image-type blocks with no `image_url` yet (which then function as
    # a pure colour-tile block). Hex string like "#FFE9C8"; null/missing
    # = no fill.
    background_color: Optional[str] = None
    # Chapter heading metadata (text blocks only)
    is_chapter: bool = False
    # Live-sync Table of Contents marker (text blocks only). Blocks with
    # this flag have their html regenerated by the editor whenever chapter
    # blocks change so the TOC always reflects the current chapter list.
    is_toc: bool = False
    # Text-style role: 'title' | 'subtitle' | 'body' (text blocks only).
    # Tagged at insertion time when the block was created via one of the
    # three "Text" toolbar presets. When the user updates a preset's
    # default style via "Save as default…", every block in the book with
    # the matching role is updated in lockstep so the typographic voice
    # stays consistent. Blocks without a role (legacy data, chapter
    # headings, blocks pasted from elsewhere) are not touched by the
    # cascade.
    text_role: Optional[str] = None



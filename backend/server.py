@api_router.post("/books/{book_id}/pdf-jobs")
async def export_pdf_start(
    book_id: str,
    request: Request,
    payload: Optional[PdfJobStartRequest] = None,
):
    """Kick off a background PDF build. Returns a job_id the client polls.
    Each call returns in ~milliseconds — no risk of proxy/CDN timeouts.

    Optional `start_page` / `end_page` (1-indexed, inclusive) export a
    contiguous slice — used by the editor's "Export range" UI to ship a
    100+ page book as several smaller PDFs that can be stitched externally.

    Note: route path deliberately avoids `.pdf` in it because some CDNs/edge
    proxies treat URLs containing `.pdf` as static-file requests and may
    short-circuit them with 404 before they reach the backend.
    """
    # Sanity-check the book exists before we spawn a worker (so the client
    # gets a 404 immediately rather than a "failed" status 20s later).
    book = await db.books.find_one({"id": book_id}, {"_id": 0, "pages": 1})
    if not book:
        raise HTTPException(404, "Book not found")
    total_pages = len(book.get("pages") or [])

    start_page = payload.start_page if payload else None
    end_page = payload.end_page if payload else None
    pdfx = bool(payload.pdfx) if payload else False
    cover_spread = bool(payload.cover_spread) if payload else False
    spine_width_in = payload.spine_width_in if payload else None
    binding_raw = (payload.binding if payload else None) or "perfect"
    binding = binding_raw.lower() if isinstance(binding_raw, str) else "perfect"
    if binding not in ("perfect", "casebound"):
        binding = "perfect"
    # DPI — snap to one of the allowed values (300/450/600). Everything
    # else (None, malformed JSON, accidental floats) falls back to the
    # safe production default of 300.
    try:
        dpi_raw = int(payload.dpi) if payload and payload.dpi is not None else 300
    except (TypeError, ValueError):
        dpi_raw = 300
    dpi = dpi_raw if dpi_raw in (300, 450, 600) else 300
    # Preview mode — clamps DPI to 150 and disables all print-oriented
    # steps (see `_run_pdf_job`). Preview overrides any print-ready
    # toggle: you can't have a "print-ready preview" — the two flags
    # are mutually exclusive by design.
    preview = bool(payload.preview) if payload else False
    if preview:
        pdfx = False
        cover_spread = False
        dpi = 150
    # Cover spread always overrides any explicit page range — the cover
    # is, by definition, only pages[0] + pages[-1].
    if cover_spread:
        start_page = None
        end_page = None
    if start_page is not None or end_page is not None:
        if start_page is None or end_page is None:
            raise HTTPException(400, "start_page and end_page must be provided together")
        if not isinstance(start_page, int) or not isinstance(end_page, int):
            raise HTTPException(400, "start_page and end_page must be integers")
        if start_page < 1 or end_page < 1:
            raise HTTPException(400, "Page numbers are 1-indexed")
        if start_page > end_page:
            raise HTTPException(400, "start_page must be <= end_page")
        if start_page > total_pages:
            raise HTTPException(400, f"start_page exceeds book length ({total_pages})")
        # end_page > total is allowed — we clamp to total_pages in the worker.

    job_id = str(uuid.uuid4())
    now = datetime.now(timezone.utc)
    await db.pdf_jobs.insert_one({
        "job_id": job_id,
        "book_id": book_id,
        "status": "pending",
        "start_page": start_page,
        "end_page": end_page,
        "pdfx": pdfx,
        "cover_spread": cover_spread,
        "spine_width_in": spine_width_in,
        "binding": binding,
        "dpi": dpi,
        "preview": preview,
        "created_at": now.isoformat(),
        # Mongo TTL index uses a real Date — not an ISO string.
        # Freshly-inserted jobs get the FAILED window. If the render
        # completes it will overwrite this with the READY window (30 min).
        # This way a pod that dies mid-render leaves a diagnosable
        # "pending" doc for 7 days instead of vanishing after 30 min.
        "expires_at": now + timedelta(seconds=_PDF_JOB_TTL_FAILED_SECONDS),
    })
    asyncio.create_task(_run_pdf_job(
        job_id, book_id, str(request.base_url).rstrip("/"),
        start_page=start_page, end_page=end_page, pdfx=pdfx,
        cover_spread=cover_spread, spine_width_in=spine_width_in,
        binding=binding,
        dpi=dpi,
        preview=preview,
    ))
    return {"job_id": job_id, "status": "pending"}



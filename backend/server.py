@api_router.get("/admin/book-diagnose/{book_id}")
async def admin_book_diagnose(
    book_id: str,
    page_no: Optional[int] = None,
    probe_bytes: bool = False,
    include_text_content: bool = False,
    user=Depends(_get_current_user_admin),
):
    """Read-only per-page inspector for a book — used to pin down which
    page/image causes WeasyPrint to hang. Zero side effects; no renders
    kicked off. Returns block layout, db.files metadata, and (optionally)
    a live byte-probe of each image referenced.

    Query params:
      * `page_no`     — restrict output to a single page number (1-based).
                        Otherwise returns every page.
      * `probe_bytes` — when `true`, fetches each image from object
                        storage and runs `Pillow.Image.open(io).verify()`.
                        Returns `reachable`, `byte_count`, `decode_ok`,
                        and — when Pillow can decode — the ACTUAL
                        (post-open) width/height. Slow on large books:
                        one HTTP roundtrip per image. Off by default.

    Failure modes surfaced:
      * `file_record: null`     — path not in db.files (orphan)
      * `size == 0`             — placeholder/failed-upload record
      * `width_px/height_px 0`  — legacy pre-validation upload
      * `probe.decode_ok=false` — Pillow couldn't parse the bytes
                                  (this is the WeasyPrint-hang smoking gun:
                                  Pillow verify passes but decode chokes,
                                  or the image is technically valid but
                                  triggers a bug in cairo/pango down the
                                  chain).

    Reads `book`, `db.files`, and optionally object-storage bytes.
    Writes NOTHING."""
    _require_admin(user)
    book = await db.books.find_one({"id": book_id}, {"_id": 0})
    if not book:
        raise HTTPException(404, f"Book {book_id} not found")

    from PIL import Image as _PILImage
    import io as _io
    # Cached Google Fonts families — from fonts_cache.GOOGLE_FONTS_URL.
    # Anything referenced on a block that is NOT in this set forces
    # WeasyPrint to fall back to the system serif at render time,
    # which under some CSS layouts is where hangs have been observed.
    # Set is derived from the family= query params in GOOGLE_FONTS_URL —
    # kept in-sync manually because fonts_cache does not expose a helper.
    _CACHED_FAMILIES = {
        "Abril Fatface", "Bebas Neue", "Bitter", "Caveat", "Cormorant Garamond",
        "Crimson Text", "Dancing Script", "DM Sans", "EB Garamond", "Fira Code",
        "Inconsolata", "Indie Flower", "JetBrains Mono", "Kalam",
        "Libre Baskerville", "Lobster", "Lora", "Merriweather", "Montserrat",
        "Nunito", "Outfit", "Pacifico", "Playfair Display", "Poppins",
        "Raleway", "Sacramento", "Work Sans",
    }

    pages = book.get("pages") or []
    all_image_paths: set[str] = set()
    for pg in pages:
        for blk in (pg.get("blocks") or []):
            if blk.get("type") == "image" and blk.get("image_path"):
                all_image_paths.add(blk["image_path"])
        # Page-level backgrounds too — some templates use these instead
        # of full-page image blocks.
        for k in ("background_image_path", "cover_image_path"):
            v = pg.get(k)
            if isinstance(v, str) and v:
                all_image_paths.add(v)

    files_by_path: dict[str, dict] = {}
    if all_image_paths:
        async for f in db.files.find(
            {"storage_path": {"$in": list(all_image_paths)}},
            {"_id": 0, "id": 1, "storage_path": 1, "original_filename": 1,
             "size": 1, "content_type": 1, "width_px": 1, "height_px": 1,
             "is_deleted": 1},
        ):
            files_by_path[f["storage_path"]] = f

    async def _probe(storage_path: str) -> dict:
        """Fetch bytes and run Pillow.verify + Image.open dimensions.
        Isolated per-image so one bad file doesn't nuke the whole scan."""
        out = {"reachable": False, "byte_count": None,
               "decode_ok": False, "decode_error": None,
               "actual_width": None, "actual_height": None}
        try:
            data, _ = await asyncio.to_thread(get_object, storage_path)
        except Exception as fe:
            out["decode_error"] = f"fetch: {type(fe).__name__}: {str(fe)[:120]}"
            return out
        if not data:
            out["decode_error"] = "fetch: empty bytes"
            return out
        out["reachable"] = True
        out["byte_count"] = len(data)
        try:
            with _PILImage.open(_io.BytesIO(data)) as im:
                # verify() throws if the image is malformed. It does NOT
                # attempt a full decode — but a decoder that returns
                # "OK" from verify() and then hangs on full decode is
                # exactly the WeasyPrint failure mode we're hunting.
                im.verify()
            # Re-open (verify() consumes the file object) to grab dims.
            with _PILImage.open(_io.BytesIO(data)) as im:
                out["actual_width"], out["actual_height"] = im.size
                out["decode_ok"] = True
        except Exception as pe:
            out["decode_error"] = f"decode: {type(pe).__name__}: {str(pe)[:180]}"
        return out

    report_pages = []
    for idx, pg in enumerate(pages):
        pno = idx + 1  # 1-based to match user-facing numbering
        if page_no is not None and pno != page_no:
            continue

        page_report = {
            "page_no": pno,
            "block_count": len(pg.get("blocks") or []),
            "background_image_path": pg.get("background_image_path"),
            "background_color": pg.get("background_color"),
            "full_bleed": pg.get("full_bleed"),
            "show_page_number": pg.get("show_page_number"),
            "page_number_font": pg.get("page_number_font"),
            "page_number_size": pg.get("page_number_size"),
            "blocks": [],
        }
        # Font-cache cross-reference for THIS page. Collect every
        # font_family declared on this page (blocks + page number font),
        # then partition into cached vs missing. Missing families are
        # the ones forcing WeasyPrint's fallback path.
        fonts_on_page: set[str] = set()

        for blk in (pg.get("blocks") or []):
            b_out = {
                "type": blk.get("type"),
                "geom": {
                    "x": blk.get("x"),
                    "y": blk.get("y"),
                    "width": blk.get("width"),
                    "height": blk.get("height"),
                    "z_index": blk.get("z_index"),
                },
            }
            if blk.get("type") == "image":
                sp = blk.get("image_path")
                b_out["storage_path"] = sp
                rec = files_by_path.get(sp) if sp else None
                b_out["file_record"] = rec  # None if orphan
                if probe_bytes and sp:
                    b_out["probe"] = await _probe(sp)
            elif blk.get("type") == "text":
                # Rough text-length signal — useful to spot a page with
                # a runaway text block that might trigger a WeasyPrint
                # layout edge case.
                html = blk.get("html") or blk.get("text") or ""
                b_out["text_length_chars"] = len(html)
                b_out["font_family"] = blk.get("font_family")
                b_out["font_size"] = blk.get("font_size")
                b_out["text_align"] = blk.get("text_align")
                b_out["color"] = blk.get("color")
                b_out["background_color"] = blk.get("background_color")
                b_out["text_role"] = blk.get("text_role")
                b_out["is_chapter"] = blk.get("is_chapter")
                b_out["is_toc"] = blk.get("is_toc")
                if blk.get("font_family"):
                    fonts_on_page.add(blk["font_family"])
                # Full text content — gated so a routine metadata call
                # doesn't drown the response with page-worth of prose.
                # When enabled, cap at 20 KB so a runaway 2 MB HTML
                # blob doesn't bloat the response either — 20 KB is
                # ~10 pages of dense text, far more than any legit
                # single block should contain.
                if include_text_content:
                    b_out["html"] = html[:20_000]
                    b_out["html_truncated"] = len(html) > 20_000
            page_report["blocks"].append(b_out)

        # Also count the page-number font if enabled.
        if pg.get("show_page_number") and pg.get("page_number_font"):
            fonts_on_page.add(pg["page_number_font"])

        # Font partition — cached vs missing.
        page_report["fonts_referenced"] = sorted(fonts_on_page)
        page_report["fonts_missing_from_cache"] = sorted(
            fonts_on_page - _CACHED_FAMILIES
        )

        # Probe page-level background too if requested.
        bg_path = pg.get("background_image_path")
        if bg_path:
            bg_rec = files_by_path.get(bg_path)
            page_report["background_file_record"] = bg_rec
            if probe_bytes:
                page_report["background_probe"] = await _probe(bg_path)
        report_pages.append(page_report)

    return {
        "book_id": book_id,
        "title": book.get("title"),
        "total_pages": len(pages),
        "probed_bytes": bool(probe_bytes),
        "include_text_content": bool(include_text_content),
        "requested_page_no": page_no,
        "cached_font_families": sorted(_CACHED_FAMILIES),
        "book_text_presets": book.get("text_presets"),
        "pages": report_pages,
    }


@api_router.post("/admin/purge-empty-files")
async def admin_purge_empty_files(
    confirm: bool = False,
    user=Depends(_get_current_user_admin),
):
    """Delete `db.files` rows where size ∈ {0, null, missing} AND the
    row is NOT soft-deleted AND no book still references its
    storage_path. Object-storage bytes are NOT touched — those expire
    through the storage backend's own GC.

    Safety:
      - `?confirm=false` (default) is a dry run: returns the counts
        without modifying the DB. Use this to preview.
      - `?confirm=true` performs the delete.
      - Rows referenced by any book are ALWAYS kept, even if 0-byte —
        they surface in the storage audit as "needs re-upload" so the
        book owner can fix them. Silently deleting them here would
        break that diagnostic surface.

    Returns the exact counts so the operator has an auditable record."""
    _require_admin(user)

    # Build the set of every storage_path referenced by ANY book. Covers
    # both block-level (image_path / image_url) and page-level
    # (background_image_path / cover_image_path). One full scan of
    # db.books, which is small.
    referenced_paths: set[str] = set()
    async for book in db.books.find({}, {"pages": 1}):
        for pg in (book.get("pages") or []):
            for k in ("background_image_path", "cover_image_path"):
                v = pg.get(k)
                if isinstance(v, str) and v:
                    referenced_paths.add(v)
            for blk in (pg.get("blocks") or []):
                for k in ("image_path", "image_url"):
                    v = blk.get(k)
                    if isinstance(v, str) and v:
                        referenced_paths.add(v)

    size_filter = {
        "is_deleted": {"$ne": True},
        "$or": [
            {"size": 0},
            {"size": None},
            {"size": {"$exists": False}},
        ],
    }

    delete_ids: list[str] = []
    kept_referenced = 0
    kept_no_id = 0
    async for f in db.files.find(size_filter, {"id": 1, "storage_path": 1}):
        fid = f.get("id")
        if not fid:
            # Defensive — every valid file record should have an id. Skip
            # so we never accidentally issue an empty $in query.
            kept_no_id += 1
            continue
        sp = f.get("storage_path")
        if sp and sp in referenced_paths:
            kept_referenced += 1
            continue
        delete_ids.append(fid)

    result_summary = {
        "confirm": confirm,
        "candidates_matched": len(delete_ids) + kept_referenced + kept_no_id,
        "kept_because_referenced": kept_referenced,
        "kept_because_no_id": kept_no_id,
        "eligible_for_delete": len(delete_ids),
        "ran_at": _now_iso(),
        "ran_by": user.get("email"),
    }
    if not confirm:
        # Dry run — report only.
        result_summary["deleted"] = 0
        result_summary["mode"] = "dry-run"
        return result_summary

    # Delete in chunks so a single 10 000-row cleanup never issues one
    # 200 KB $in query — 500 ids per batch is well within the driver's
    # comfortable range.
    deleted = 0
    BATCH = 500
    for i in range(0, len(delete_ids), BATCH):
        chunk = delete_ids[i:i + BATCH]
        res = await db.files.delete_many({"id": {"$in": chunk}})
        deleted += res.deleted_count
    result_summary["deleted"] = deleted
    result_summary["mode"] = "executed"
    logging.info(
        "admin_purge_empty_files by %s: deleted %d orphaned empty file records",
        user.get("email"), deleted,
    )
    return result_summary


@api_router.get("/books/{book_id}/file-health")
async def book_file_health(book_id: str, request: Request):
    """Per-book pre-export file-health check. Visible to any logged-in
    user (the auth middleware already guards `/api/*` for them) — the
    book owner has a right to know which of THEIR images are problematic
    before they spend render time. Returns the same shape the export
    flow's pre-flight warning consumes."""
    if not getattr(request.state, "user_id", None):
        raise HTTPException(401, "Authentication required")

    book = await db.books.find_one({"id": book_id}, {"_id": 0, "pages": 1, "title": 1})
    if not book:
        raise HTTPException(404, "Book not found")

    # Collect every (path, page_no) reference in the book.
    refs: list[tuple[str, int]] = []
    for page_idx, page in enumerate(book.get("pages") or []):
        for block in (page.get("blocks") or []):
            if block.get("type") == "image":
                p = block.get("image_path")
                if p:
                    refs.append((p, page_idx + 1))

    if not refs:
        return {"problems": [], "checked": 0}

    paths = list({p for p, _ in refs})
    rows = await db.files.find(
        {"storage_path": {"$in": paths}, "is_deleted": {"$ne": True}},
        {"_id": 0, "storage_path": 1, "original_filename": 1,
         "width_px": 1, "height_px": 1},
    ).to_list(len(paths))
    by_path = {r["storage_path"]: r for r in rows}

    def _basename(path: str) -> str:
        return (path or "").rsplit("/", 1)[-1] or path

    problems: list[dict] = []
    for path, page_no in refs:
        row = by_path.get(path)
        if row is None:
            problems.append({
                "storage_path": path,
                "filename": _basename(path),
                "page_no": page_no,
                "issue": "missing",
            })
            continue
        w, h = row.get("width_px"), row.get("height_px")
        if not w or not h or w <= 0 or h <= 0:
            problems.append({
                "storage_path": path,
                "filename": row.get("original_filename") or _basename(path),
                "page_no": page_no,
                "issue": "no_dimensions",
            })

    return {"problems": problems, "checked": len(refs)}



@app.on_event("startup")
async def startup():
    try:
        init_storage()
        logging.info("Storage initialized")
    except Exception as e:
        logging.error(f"Storage init failed: {e}")
    # Auth: indexes + idempotent admin seed. Must run BEFORE the app starts
    # serving real traffic so the first login request finds the admin row.
    try:
        from auth import ensure_indexes, seed_admin
        await ensure_indexes(db)
        await seed_admin(db)
    except Exception as e:
        logging.error(f"Auth bootstrap failed: {e}")
    # Ensure the pdf_jobs collection has its TTL + lookup indexes.
    try:
        await _ensure_pdf_jobs_indexes()
    except Exception as e:
        logging.warning(f"pdf_jobs index setup deferred: {e}")
    # PDF export requires Chromium, but downloading it (~200 MB, ~20 s) must
    # NEVER block FastAPI's startup — uvicorn's lifespan has a hard timeout
    # and a slow install would leave the entire app unresponsive (book CRUD,
    # asset list, everything). Kick the install off as a background task so
    # the API answers requests immediately; the PDF endpoint waits on the
    # same task lazily.
    import asyncio as _asyncio
    from pdf_builder import ensure_chromium_installed

    async def _bg_install():
        try:
            await ensure_chromium_installed()
        except Exception as e:
            logging.warning(f"Chromium background install failed (will retry on first PDF request): {e}")

    _asyncio.create_task(_bg_install())

    # Warm the Google Fonts cache in the background. First export
    # request would otherwise pay ~10-30s downloading ~50+ WOFF2
    # files synchronously — and Support pinpointed that fetch as
    # the cause of full-book hangs. After warm-up every render
    # uses inlined base64 data URIs (no network during PDF build).
    try:
        from fonts_cache import warm_cache_async
        warm_cache_async()
    except Exception as e:
        logging.warning(f"fonts_cache warm-up could not start: {e}")

    # Background sweeper: fail any pdf_job that hasn't progressed in 10 min.
    # Without this, a job whose worker died (pod restart, OOM kill, or a
    # Chromium hang we missed) sits in `status="pending"` forever and the
    # UI shows an infinite spinner. The sweeper turns those zombies into
    # explicit failures the client can show + recover from.
    async def _bg_sweep_stuck_jobs():
        from datetime import datetime, timezone, timedelta
        while True:
            try:
                cutoff = datetime.now(timezone.utc) - timedelta(minutes=10)
                cutoff_iso = cutoff.isoformat()
                # `stage_at` updates every time `_run_pdf_job` calls
                # `_emit(...)`. If it's older than 10 min the worker is
                # almost certainly dead — Chromium chunks rarely take
                # longer than 90s each thanks to the new wall-clock guard.
                result = await db.pdf_jobs.update_many(
                    {
                        "status": "pending",
                        "$or": [
                            {"stage_at": {"$lt": cutoff_iso}},
                            # Older jobs never wrote stage_at — fall back
                            # to created_at so we don't miss them.
                            {"stage_at": {"$exists": False}, "created_at": {"$lt": cutoff_iso}},
                        ],
                    },
                    {"$set": {
                        "status": "failed",
                        "error": (
                            "Export timed out — no progress for 10 minutes. "
                            "The render worker likely crashed. Try again, "
                            "or pick a smaller page range / lower DPI."
                        ),
                    }},
                )
                if result.modified_count:
                    logging.warning(
                        "PDF sweep: marked %d stuck job(s) as failed",
                        result.modified_count,
                    )
            except Exception as e:
                logging.warning(f"PDF sweep iteration failed: {e}")
            # 60s cadence — fast enough that users see a real error in
            # under 11 min, slow enough not to hammer Mongo.
            await _asyncio.sleep(60)

    _asyncio.create_task(_bg_sweep_stuck_jobs())


